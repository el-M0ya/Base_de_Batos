BEGIN;

-- ============================================================
-- 1. VALIDATION
-- Registro de la validación de una rutina por un entrenador.
-- ============================================================

CREATE TABLE validation (
    id_validation BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_routine BIGINT NOT NULL REFERENCES routine(id_routine),
    id_trainer BIGINT NOT NULL REFERENCES trainer(id_trainer),
    validation_date TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    comments TEXT
);


-- ============================================================
-- 2. ASSIGNMENT
-- Asignación de una rutina a un cliente.
-- ============================================================

CREATE TABLE assignment (
    id_assignment BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_routine BIGINT NOT NULL REFERENCES routine(id_routine),
    id_client BIGINT NOT NULL REFERENCES client(id_client),
    assignment_date DATE NOT NULL DEFAULT CURRENT_DATE,
    end_date DATE
);


-- ============================================================
-- 3. SESSION
-- Cada sesión pertenece a una asignación existente.
-- Se conserva el historial de sesiones.
-- ============================================================

CREATE TABLE session (
    id_session BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_assignment BIGINT NOT NULL REFERENCES assignment(id_assignment),
    session_date DATE NOT NULL DEFAULT CURRENT_DATE,
    start_time TIMESTAMP NOT NULL,
    end_time TIMESTAMP,
    intensity_perceived INTEGER
);


-- ============================================================
-- 4. REQUEST
-- Solicitud de ajuste realizada por un cliente.
-- ============================================================

CREATE TABLE request (
    id_request BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_client BIGINT NOT NULL REFERENCES client(id_client),
    request_date TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    description TEXT NOT NULL,
    status VARCHAR(30) NOT NULL DEFAULT 'pending'
);


-- ============================================================
-- 5. ADJUSTMENT_RESULT
-- Resultado asociado a la solicitud que lo originó.
-- ============================================================

CREATE TABLE adjustment_result (
    id_adjustment_result BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_request BIGINT NOT NULL UNIQUE
        REFERENCES request(id_request),
    result_description TEXT NOT NULL,
    result_date TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP
);

COMMIT;