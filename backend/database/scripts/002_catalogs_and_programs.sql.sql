-- =============================================================================
-- 002_catalogs_and_programs.sql
-- Project: Planificacion
-- Description:
--   Creates workout program and exercise catalogs, together with the
--   relationship between workout programs and muscle groups.
--
-- Tables:
--   1. workout_program
--   2. muscle_group
--   3. exercise_type
--   4. covers
--
-- Notes:
--   - Intensity is an attribute of routine, not a separate catalog.
--   - Catalog names and workout program names must be unique.
--   - A workout program can cover multiple muscle groups.
--   - A muscle group can belong to multiple workout programs.
-- =============================================================================

BEGIN;

-- =============================================================================
-- 1. MUSCLE GROUP
-- =============================================================================

CREATE TABLE muscle_group (
    id_muscle_group BIGINT GENERATED BY DEFAULT AS IDENTITY,
    name VARCHAR(100) NOT NULL,

    CONSTRAINT pk_muscle_group
        PRIMARY KEY (id_muscle_group),

    CONSTRAINT uq_muscle_group_name
        UNIQUE (name),

    CONSTRAINT chk_muscle_group_name
        CHECK (BTRIM(name) <> '')      -- Delete spaces
);

-- =============================================================================
-- 2. EXERCISE TYPE
-- =============================================================================

CREATE TABLE exercise_type (
    id_exercise_type BIGINT GENERATED BY DEFAULT AS IDENTITY,
    name VARCHAR(100) NOT NULL,

    CONSTRAINT pk_exercise_type
        PRIMARY KEY (id_exercise_type),

    CONSTRAINT uq_exercise_type_name
        UNIQUE (name),

    CONSTRAINT chk_exercise_type_name
        CHECK (BTRIM(name) <> '')      -- Delete spaces names
);

-- =============================================================================
-- 2.1 INTENSITY LEVEL
-- Scripts 006 (unique name constraint) and 008 (seed data) reference this
-- catalog, and the exercise classification needs it, but the table was missing
-- from the E1 scripts. Created here so the schema can be applied in order.
-- =============================================================================

CREATE TABLE intensity_level (
    id_intensity_level BIGINT GENERATED BY DEFAULT AS IDENTITY,
    name VARCHAR(100) NOT NULL,

    CONSTRAINT pk_intensity_level
        PRIMARY KEY (id_intensity_level),

    CONSTRAINT uq_intensity_level_name
        UNIQUE (name),

    CONSTRAINT chk_intensity_level_name
        CHECK (BTRIM(name) <> '')
);

-- =============================================================================
-- 3. WORKOUT PROGRAM
-- =============================================================================

CREATE TABLE workout_program (
    id_workout_program BIGINT GENERATED BY DEFAULT AS IDENTITY,
    name VARCHAR(150) NOT NULL,
    objective TEXT NOT NULL,

    CONSTRAINT pk_workout_program
        PRIMARY KEY (id_workout_program),

    CONSTRAINT uq_workout_program_name
        UNIQUE (name),

    CONSTRAINT chk_workout_program_name
        CHECK (BTRIM(name) <> ''),

    CONSTRAINT chk_workout_program_objective
        CHECK (BTRIM(objective) <> '')
);

-- =============================================================================
-- 4. COVERS
-- Relationship between workout programs and muscle groups.
-- =============================================================================

CREATE TABLE covers (
    id_workout_program BIGINT NOT NULL,
    id_muscle_group BIGINT NOT NULL,

    CONSTRAINT pk_covers
        PRIMARY KEY (id_workout_program, id_muscle_group),

    CONSTRAINT fk_covers_workout_program
        FOREIGN KEY (id_workout_program)
        REFERENCES workout_program (id_workout_program),

    CONSTRAINT fk_covers_muscle_group
        FOREIGN KEY (id_muscle_group)
        REFERENCES muscle_group (id_muscle_group)
);

COMMIT;