-- -----------------------------------------------------------------------------
-- This script creates the following tables for Module 4 (Routines & Structure):
--   - routine             (R14) - Workout routine header & lifecycle status
--   - parameters_routine  (R15) - Generation parameters log for each routine (1:1)
--   - contains            (R16) - Relational composition of exercises within routines
--   - routine_structure   (R17) - JSONB document store for variable block hierarchies (1:1)
--
-- Design notes:
--   - Follows strict 3NF for relational parts, complemented by routine_structure (JSONB)
--     to accommodate variable hierarchies (warm-ups, circuits, sets, rest intervals).
--   - Foreign keys use ON UPDATE RESTRICT ON DELETE RESTRICT for data safety.
--   - Atomic transaction guarantees routine and routine_structure consistency.
-- -----------------------------------------------------------------------------

BEGIN;

-- -----------------------------------------------------------------------------
-- Table: routine
-- -----------------------------------------------------------------------------
CREATE TABLE IF NOT EXISTS routine (
    id_routine            INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    status                VARCHAR(30)         NOT NULL DEFAULT 'PENDING_REVIEW',
    creation_date         DATE                NOT NULL DEFAULT CURRENT_DATE,
    id_workout_program    INTEGER             NOT NULL,
    id_trainer_creator    INTEGER             NOT NULL,
    id_client             INTEGER,

    CONSTRAINT fk_routine_workout_program
        FOREIGN KEY (id_workout_program)
        REFERENCES workout_program (id_workout_program)
        ON UPDATE RESTRICT
        ON DELETE RESTRICT,

    CONSTRAINT fk_routine_trainer_creator
        FOREIGN KEY (id_trainer_creator)
        REFERENCES trainer (id_trainer)
        ON UPDATE RESTRICT
        ON DELETE RESTRICT,

    CONSTRAINT fk_routine_client
        FOREIGN KEY (id_client)
        REFERENCES client (id_client)
        ON UPDATE RESTRICT
        ON DELETE RESTRICT,

    CONSTRAINT chk_routine_status
        CHECK (status IN ('DRAFT', 'PENDING_REVIEW', 'APPROVED', 'REJECTED'))
);

-- Indexes for FK performance (non-leading FK columns)
CREATE INDEX IF NOT EXISTS idx_routine_workout_program ON routine (id_workout_program);
CREATE INDEX IF NOT EXISTS idx_routine_trainer_creator ON routine (id_trainer_creator);
CREATE INDEX IF NOT EXISTS idx_routine_client ON routine (id_client);

COMMENT ON TABLE  routine IS 'Header entity for workout routines, tracking lifecycle status and creators.';
COMMENT ON COLUMN routine.id_routine         IS 'Primary key of the routine.';
COMMENT ON COLUMN routine.status             IS 'Lifecycle status (DRAFT, PENDING_REVIEW, APPROVED, REJECTED).';
COMMENT ON COLUMN routine.creation_date      IS 'Date the routine was generated or created.';
COMMENT ON COLUMN routine.id_workout_program IS 'Workout program this routine belongs to (FK).';
COMMENT ON COLUMN routine.id_trainer_creator IS 'Trainer who created/generated the routine (FK).';
COMMENT ON COLUMN routine.id_client          IS 'Target client for personalized routines, if applicable (FK).';


-- -----------------------------------------------------------------------------
-- Table: parameters_routine
-- -----------------------------------------------------------------------------
CREATE TABLE IF NOT EXISTS parameters_routine (
    id_routine            INTEGER             PRIMARY KEY,
    total_exercises       INTEGER             NOT NULL,
    intensity_level       VARCHAR(50)         NOT NULL,
    cardio_ratio          NUMERIC(5,2)        NOT NULL,
    strength_ratio        NUMERIC(5,2)        NOT NULL,

    CONSTRAINT fk_parameters_routine_routine
        FOREIGN KEY (id_routine)
        REFERENCES routine (id_routine)
        ON UPDATE RESTRICT
        ON DELETE RESTRICT,

    CONSTRAINT chk_parameters_routine_total_exercises
        CHECK (total_exercises > 0),

    CONSTRAINT chk_parameters_routine_intensity_not_empty
        CHECK (TRIM(intensity_level) <> ''),

    CONSTRAINT chk_parameters_routine_ratios
        CHECK (cardio_ratio >= 0 AND strength_ratio >= 0 AND (cardio_ratio + strength_ratio) <= 100)
);

COMMENT ON TABLE  parameters_routine IS 'Log of historical generation parameters used to produce each routine (1:1 with routine).';
COMMENT ON COLUMN parameters_routine.id_routine       IS 'Primary key and foreign key referencing routine(id_routine).';
COMMENT ON COLUMN parameters_routine.total_exercises  IS 'Target number of exercises requested during generation.';
COMMENT ON COLUMN parameters_routine.intensity_level  IS 'Intensity level constraint requested.';
COMMENT ON COLUMN parameters_routine.cardio_ratio     IS 'Percentage allocation for cardio exercises.';
COMMENT ON COLUMN parameters_routine.strength_ratio   IS 'Percentage allocation for strength exercises.';


-- -----------------------------------------------------------------------------
-- Table: contains
-- -----------------------------------------------------------------------------
CREATE TABLE IF NOT EXISTS contains (
    id_routine            INTEGER             NOT NULL,
    id_exercise           INTEGER             NOT NULL,
    execution_order       INTEGER             NOT NULL,
    sets                  INTEGER             NOT NULL,
    repetitions           INTEGER             NOT NULL,
    rest_time_seconds     INTEGER             NOT NULL DEFAULT 60,

    CONSTRAINT pk_contains
        PRIMARY KEY (id_routine, id_exercise, execution_order),

    CONSTRAINT fk_contains_routine
        FOREIGN KEY (id_routine)
        REFERENCES routine (id_routine)
        ON UPDATE RESTRICT
        ON DELETE RESTRICT,

    CONSTRAINT fk_contains_exercise
        FOREIGN KEY (id_exercise)
        REFERENCES exercise (id_exercise)
        ON UPDATE RESTRICT
        ON DELETE RESTRICT,

    CONSTRAINT chk_contains_execution_order
        CHECK (execution_order > 0),

    CONSTRAINT chk_contains_sets
        CHECK (sets > 0),

    CONSTRAINT chk_contains_repetitions
        CHECK (repetitions > 0),

    CONSTRAINT chk_contains_rest_time
        CHECK (rest_time_seconds >= 0)
);

-- Index for FK on id_exercise (id_routine is already leading column of PK)
CREATE INDEX IF NOT EXISTS idx_contains_exercise ON contains (id_exercise);

COMMENT ON TABLE  contains IS 'Relational composition mapping exercises to routines with explicit order, sets, reps, and rest.';
COMMENT ON COLUMN contains.id_routine        IS 'Foreign key referencing routine(id_routine).';
COMMENT ON COLUMN contains.id_exercise       IS 'Foreign key referencing exercise(id_exercise).';
COMMENT ON COLUMN contains.execution_order   IS 'Sequential position of the exercise in the routine.';
COMMENT ON COLUMN contains.sets              IS 'Number of set repetitions.';
COMMENT ON COLUMN contains.repetitions       IS 'Number of movement repetitions per set.';
COMMENT ON COLUMN contains.rest_time_seconds IS 'Rest duration between sets in seconds.';


-- -----------------------------------------------------------------------------
-- Table: routine_structure
-- -----------------------------------------------------------------------------
CREATE TABLE IF NOT EXISTS routine_structure (
    id_routine            INTEGER             PRIMARY KEY,
    structure_json        JSONB               NOT NULL,

    CONSTRAINT fk_routine_structure_routine
        FOREIGN KEY (id_routine)
        REFERENCES routine (id_routine)
        ON UPDATE RESTRICT
        ON DELETE RESTRICT,

    CONSTRAINT chk_routine_structure_json_object
        CHECK (jsonb_typeof(structure_json) = 'object')
);

COMMENT ON TABLE  routine_structure IS 'Stores the nested JSONB structure for variable block hierarchies (warm-ups, circuits, sets, rest).';
COMMENT ON COLUMN routine_structure.id_routine     IS 'Primary key and foreign key referencing routine(id_routine).';
COMMENT ON COLUMN routine_structure.structure_json IS 'JSONB document representing the nested tree of blocks, circuits, and exercises.';

COMMIT;
