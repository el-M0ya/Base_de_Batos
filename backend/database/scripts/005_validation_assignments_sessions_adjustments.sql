-- 005_validation_assignments_sessions_adjustments.sql
-- PostgreSQL
-- Creates the validation, assignment, session, request and adjustment-result
-- relations defined in the approved MERX.
--
-- Prerequisite: the base relations must already exist:
--   routine(id_routine), room_chief(id_room_chief), client(id_client),
--   trainer(id_trainer)
--
-- This script focuses on table structure, primary keys and referential
-- integrity. Domain, uniqueness and temporal business rules are handled
-- separately by the integrity-constraints script.

BEGIN;

CREATE TABLE IF NOT EXISTS validate (
    id_validation   INTEGER GENERATED BY DEFAULT AS IDENTITY,
    id_routine      INTEGER NOT NULL,
    id_room_chief   INTEGER NOT NULL,
    fecha_validacion DATE NOT NULL,
    decision        VARCHAR(30) NOT NULL,
    observaciones   TEXT,

    CONSTRAINT pk_validate
        PRIMARY KEY (id_validation),

    CONSTRAINT fk_validate_routine
        FOREIGN KEY (id_routine)
        REFERENCES routine (id_routine)
        ON UPDATE CASCADE
        ON DELETE RESTRICT,

    CONSTRAINT fk_validate_room_chief
        FOREIGN KEY (id_room_chief)
        REFERENCES room_chief (id_room_chief)
        ON UPDATE CASCADE
        ON DELETE RESTRICT
);

CREATE TABLE IF NOT EXISTS assignment (
    id_assignment    INTEGER GENERATED BY DEFAULT AS IDENTITY,
    id_routine       INTEGER NOT NULL,
    id_client        INTEGER NOT NULL,
    fecha_asignacion DATE NOT NULL,
    fecha_fin        DATE,

    CONSTRAINT pk_assignment
        PRIMARY KEY (id_assignment),

    CONSTRAINT fk_assignment_routine
        FOREIGN KEY (id_routine)
        REFERENCES routine (id_routine)
        ON UPDATE CASCADE
        ON DELETE RESTRICT,

    CONSTRAINT fk_assignment_client
        FOREIGN KEY (id_client)
        REFERENCES client (id_client)
        ON UPDATE CASCADE
        ON DELETE RESTRICT
);

CREATE TABLE IF NOT EXISTS session (
    id_session          INTEGER GENERATED BY DEFAULT AS IDENTITY,
    id_assignment       INTEGER NOT NULL,
    fecha_sesion        DATE NOT NULL,
    hora_inicio         TIME NOT NULL,
    hora_fin            TIME NOT NULL,
    intensidad_percibida VARCHAR(30),
    completada          BOOLEAN NOT NULL,
    observaciones       TEXT,

    CONSTRAINT pk_session
        PRIMARY KEY (id_session),

    CONSTRAINT fk_session_assignment
        FOREIGN KEY (id_assignment)
        REFERENCES assignment (id_assignment)
        ON UPDATE CASCADE
        ON DELETE RESTRICT
);

CREATE TABLE IF NOT EXISTS request (
    id_request       INTEGER GENERATED BY DEFAULT AS IDENTITY,
    id_client        INTEGER NOT NULL,
    id_routine       INTEGER NOT NULL,
    id_trainer       INTEGER NOT NULL,
    fecha_solicitud  DATE NOT NULL,
    motivo           TEXT NOT NULL,
    estado           VARCHAR(30) NOT NULL,

    CONSTRAINT pk_request
        PRIMARY KEY (id_request),

    CONSTRAINT fk_request_client
        FOREIGN KEY (id_client)
        REFERENCES client (id_client)
        ON UPDATE CASCADE
        ON DELETE RESTRICT,

    CONSTRAINT fk_request_routine
        FOREIGN KEY (id_routine)
        REFERENCES routine (id_routine)
        ON UPDATE CASCADE
        ON DELETE RESTRICT,

    CONSTRAINT fk_request_trainer
        FOREIGN KEY (id_trainer)
        REFERENCES trainer (id_trainer)
        ON UPDATE CASCADE
        ON DELETE RESTRICT
);

CREATE TABLE IF NOT EXISTS adjustment_result (
    id_request           INTEGER NOT NULL,
    fecha_respuesta      DATE NOT NULL,
    descripcion_ajuste   TEXT NOT NULL,
    id_routine_resultante INTEGER NOT NULL,
    id_trainer_resolutor INTEGER NOT NULL,

    -- A request can have at most one result; its identifier is also
    -- the primary key of this dependent relation.
    CONSTRAINT pk_adjustment_result
        PRIMARY KEY (id_request),

    CONSTRAINT fk_adjustment_result_request
        FOREIGN KEY (id_request)
        REFERENCES request (id_request)
        ON UPDATE CASCADE
        ON DELETE RESTRICT,

    CONSTRAINT fk_adjustment_result_routine
        FOREIGN KEY (id_routine_resultante)
        REFERENCES routine (id_routine)
        ON UPDATE CASCADE
        ON DELETE RESTRICT,

    CONSTRAINT fk_adjustment_result_trainer
        FOREIGN KEY (id_trainer_resolutor)
        REFERENCES trainer (id_trainer)
        ON UPDATE CASCADE
        ON DELETE RESTRICT
);

COMMIT;
